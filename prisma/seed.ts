async function main() {
  const provinceIdsByCode = new Map<string, string>();
  const districtIdsByCode = new Map<string, string>();

  for (const province of sriLankanProvinces) {
    const savedProvince = await prisma.province.upsert({
      where: {
        code: province.code,
      },
      update: {
        name: province.name,
        displayOrder: province.displayOrder,
        isActive: true,
      },
      create: {
        name: province.name,
        code: province.code,
        displayOrder: province.displayOrder,
        isActive: true,
      },
    });

    provinceIdsByCode.set(province.code, savedProvince.id);
  }

  for (const district of sriLankanDistricts) {
    const provinceId = provinceIdsByCode.get(district.provinceCode);

    if (!provinceId) {
      throw new Error(
        `Province "${district.provinceCode}" not found for district "${district.name}"`,
      );
    }

    const savedDistrict = await prisma.district.upsert({
      where: {
        code: district.code,
      },
      update: {
        name: district.name,
        provinceId,
        displayOrder: district.displayOrder,
        isActive: true,
      },
      create: {
        name: district.name,
        code: district.code,
        provinceId,
        displayOrder: district.displayOrder,
        isActive: true,
      },
    });

    districtIdsByCode.set(district.code, savedDistrict.id);
  }

  for (const city of sriLankanCities) {
    const districtId = districtIdsByCode.get(city.districtCode);

    if (!districtId) {
      throw new Error(
        `District "${city.districtCode}" not found for city "${city.name}"`,
      );
    }

    await prisma.city.upsert({
      where: {
        code: city.code,
      },
      update: {
        name: city.name,
        districtId,
        displayOrder: city.displayOrder,
        isActive: true,
      },
      create: {
        name: city.name,
        code: city.code,
        districtId,
        displayOrder: city.displayOrder,
        isActive: true,
      },
    });
  }

  console.log(
    `Seeded ${sriLankanProvinces.length} Sri Lankan provinces successfully.`,
  );
  console.log(
    `Seeded ${sriLankanDistricts.length} Sri Lankan districts successfully.`,
  );
  console.log(
    `Seeded ${sriLankanCities.length} Sri Lankan cities successfully.`,
  );
}

main()
  .catch((error) => {
    console.error('Province/District/City seed failed:', error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
