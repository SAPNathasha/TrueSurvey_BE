function toCityCode(districtCode: string, cityName: string) {
  return `${districtCode}_${cityName
    .replace(/['’]/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase()}`;
}

function createCities(districtCode: string, names: readonly string[]) {
  return names.map((name, index) => ({
    name,
    code: toCityCode(districtCode, name),
    districtCode,
    displayOrder: index + 1,
  }));
}

